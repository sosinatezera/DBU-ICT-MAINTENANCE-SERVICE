  var FALLBACK_LANG = 'en';

  function getLang() {
    var v = localStorage.getItem(LANG_STORAGE_KEY);
    return (v === 'en' || v === 'am') ? v : FALLBACK_LANG;
  }

  function setLang(lang, save) {
    if (lang !== 'en' && lang !== 'am') lang = FALLBACK_LANG;
    if (save !== false) localStorage.setItem(LANG_STORAGE_KEY, lang);
    document.documentElement.setAttribute('lang', lang);
    applyLanguage(document);
    syncSelector(lang);
    var evt = new CustomEvent('lang:changed', { detail: { lang: lang } });
    document.dispatchEvent(evt);
  }

  function toggleLang() {
    setLang(getLang() === 'am' ? 'en' : 'am');
    return getLang();
  }

  function t(label) {
    var lang = getLang();
    var table = DICT[lang] || DICT[FALLBACK_LANG];
    if (table && Object.prototype.hasOwnProperty.call(table, label)) {
      return table[label];
    }
    var en = DICT[FALLBACK_LANG] || {};
    return Object.prototype.hasOwnProperty.call(en, label) ? en[label] : null;
  }

  function applyLanguage(root) {
    var scope = root && root.querySelectorAll ? root : document;
    var lang = getLang();

    scope.querySelectorAll('[data-i18n]').forEach(function (el) {
      var key = el.getAttribute('data-i18n');
      if (!key) return;
      var txt = t(key);
      if (txt !== null) el.textContent = txt;
    });

    scope.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
      var key = el.getAttribute('data-i18n-placeholder');
      if (!key) return;
      var txt = t(key);
      if (txt !== null) el.setAttribute('placeholder', txt);
    });

    scope.querySelectorAll('[data-i18n-title]').forEach(function (el) {
      var key = el.getAttribute('data-i18n-title');
      if (!key) return;
      var txt = t(key);
      if (txt !== null) el.setAttribute('title', txt);
    });
  }

  function syncSelector(lang) {
    var sel = document.querySelector('#langSwitch');
    if (!sel) return;
    if (sel.tagName === 'SELECT') {
      sel.value = lang;
    } else {
      sel.setAttribute('data-value', lang);
    }
  }

  function buildSwitch() {
    var lang = getLang();
    var wrapper = document.createElement('div');
    wrapper.className = 'lang-switch';
    wrapper.setAttribute('id', 'langSwitch');

    var options = [
      ['en', DICT[FALLBACK_LANG]['lang.en']],
      ['am', DICT.am['lang.am']]
    ];

    var sel = document.createElement('select');
    sel.className = 'form-select form-select-sm lang-select';
    sel.setAttribute('aria-label', 'Language');
    options.forEach(function (o) {
      var op = document.createElement('option');
      op.value = o[0];
      op.textContent = o[1];
      sel.appendChild(op);
    });
    sel.value = lang;
    sel.addEventListener('change', function () { setLang(sel.value); });
    wrapper.appendChild(sel);
    return wrapper;
  }

  function injectLangSwitch() {
    if (document.querySelector('#langSwitch')) return;

    /* No language switcher on login/register pages. */
    if (document.body && document.body.classList.contains('auth-body')) return;

    var target = document.querySelector('.lang-switch-container');
    if (target) {
      target.appendChild(buildSwitch());
      return;
    }

    /* Public navbar action area (index.html) */
    var actions = document.querySelector('.main-navbar .d-flex.align-items-center.gap-2.mt-2.mt-lg-0');
    if (actions) {
      var before = actions.firstElementChild;
      var s = buildSwitch();
      if (before) actions.insertBefore(s, before);
      else actions.appendChild(s);
      return;
    }

    /* Auth pages: attach to the form header/card if present */
    var authCard = document.querySelector('.auth-body .card, .auth-card');
    if (authCard) {
      var s2 = buildSwitch();
      var cardBody = authCard.querySelector('.card-body');
      (cardBody || authCard).appendChild(s2);
    }
  }

  function initLang() {
    setLang(getLang(), false);
    injectLangSwitch();
  }

  /* Expose a few global helpers (namespaced to avoid collisions). */
  window.getLang = getLang;
  window.setLang = setLang;
  window.toggleLang = toggleLang;
  window.t = t;
  window.applyLanguage = applyLanguage;
  window.initLang = initLang;

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', initLang);
  } else {
    initLang();
  }
